use serde::{Deserialize, Serialize};

use agent_loadgen_core::TraceRequest;

/// The planned relationship between user-configured top-level streams and generated subagents.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct GeneratedSessionTopology {
    /// User-configured top-level agent session trees in this finite plan.
    pub configured_top_level_sessions: usize,
    /// User-configured top-level session streams active at once; absent for arrivals.
    pub configured_concurrent_sessions: Option<usize>,
    /// Descendant protocol sessions generated by delegation and swarm actions.
    pub generated_subagent_sessions: usize,
    /// All protocol sessions sent to the target, including descendants.
    pub total_protocol_sessions: usize,
}

/// One top-level session tree with tree-local node ordinals.
#[derive(Debug, Clone, Serialize)]
pub struct PlannedTree {
    pub index: usize,
    /// For streams, the delay after the slot's previous tree before this one starts.
    pub restart_delay_ms: u64,
    /// The root session's last request, which ends the tree for its stream.
    pub root_final: usize,
    pub total_input_tokens: u64,
    pub sessions: Vec<GeneratedSession>,
    /// Node 0 is the tree's first request and has no dependencies.
    pub nodes: Vec<GeneratedNode>,
    pub compaction_operations: Vec<GeneratedCompactionOperation>,
}

#[derive(Debug, Clone, Serialize)]
pub struct GeneratedSession {
    pub session_id: String,
    pub parent_session_id: Option<String>,
    pub depth: usize,
    /// The top-level session tree this session belongs to.
    pub top_level_session_index: usize,
    /// The configured top-level stream that owns this session tree.
    pub top_level_stream_slot: usize,
}

#[derive(Debug, Clone, Serialize)]
pub struct GeneratedNode {
    pub node_id: String,
    pub action: String,
    pub dependencies: Vec<usize>,
    pub delay_after_dependencies_ms: u64,
    /// Scheduled ramp-up timestamp for the first tree in a top-level stream.
    pub initial_arrival_ms: Option<u64>,
    pub window_epoch: usize,
    pub tool_events: Vec<GeneratedToolEvent>,
    pub spawned_session_ids: Vec<String>,
    pub output_budget_tokens: Option<u32>,
    pub compaction_attempt: Option<GeneratedCompactionAttempt>,
    /// True for the last model request of its protocol session.
    pub session_final: bool,
    pub request: TraceRequest,
}

#[derive(Debug, Clone, Copy, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum CompactionExpectedEffect {
    NoMutationAborted,
    ApplyOnce,
    DuplicateNoop,
}

#[derive(Debug, Clone, Serialize)]
pub struct GeneratedCompactionAttempt {
    pub operation_id: String,
    pub phase: String,
    pub attempt: usize,
    pub expected_effect: CompactionExpectedEffect,
    pub abort_after_ms: Option<u64>,
}

#[derive(Debug, Clone, Serialize)]
pub struct GeneratedCompactionOperation {
    pub operation_id: String,
    pub session_id: String,
    pub phase: String,
    pub attempts: Vec<usize>,
    pub applied_attempt: usize,
    pub expected_apply_count: usize,
}

#[derive(Debug, Clone, Serialize)]
pub struct GeneratedToolEvent {
    pub class: String,
    pub latency_ms: u64,
    pub result_tokens: u64,
    pub failed: bool,
    pub retried: bool,
}
