#[derive(Debug, Clone)]
pub struct ReplayOptions {
    pub header_dialect: HeaderDialect,
    /// Add `x-dynamo-session-final: true` to each session's last request.
    pub dynamo_session_final: bool,
    pub model: String,
    pub target: String,
    pub output_dir: PathBuf,
    pub timeout: Duration,
    pub static_headers: Vec<(String, String)>,
    /// Stop dispatching after this long, wait for in-flight requests, and end.
    pub stop_after: Option<Duration>,
}

#[derive(Debug, Clone, Deserialize, Serialize)]
pub(crate) struct RequestResult {
    pub ordinal: usize,
    pub source_request_id: String,
    pub source_x_request_id: Option<String>,
    pub replay_request_id: String,
    pub session_id: Option<String>,
    pub parent_session_id: Option<String>,
    pub scheduled_offset_ms: f64,
    pub scheduler_wake_offset_ms: f64,
    pub scheduler_wake_lag_ms: f64,
    pub dispatch_offset_ms: f64,
    pub dispatch_lag_ms: f64,
    pub local_admission_lag_ms: f64,
    pub expected_input_tokens: usize,
    pub expected_output_tokens: Option<u32>,
    pub observed_output_tokens: Option<u64>,
    pub output_length_match: Option<bool>,
    pub compaction_operation_id: Option<String>,
    pub compaction_phase: Option<String>,
    pub compaction_attempt: Option<usize>,
    pub compaction_expected_effect: Option<CompactionExpectedEffect>,
    pub planned_abort_match: Option<bool>,
    pub status_code: Option<u16>,
    pub ttft_ms: Option<f64>,
    pub total_time_ms: f64,
    pub response_headers: BTreeMap<String, String>,
    pub error: Option<String>,
}

#[derive(Debug, Clone, Serialize)]
pub struct RunSummary {
    pub run_id: String,
    pub header_dialect: HeaderDialect,
    pub dynamo_session_final: bool,
    pub model: String,
    pub target: String,
    /// Requests the client allows in flight at once, sized from the
    /// open-file limit so it guards the client, not the load.
    pub in_flight_limit: usize,
    /// Most requests in flight at once. If it equals `in_flight_limit`, the
    /// client held back requests the profile would have sent.
    pub peak_in_flight: usize,
    /// HTTP version of the connection to the target: `h2c`, `http/1.1`, or `h2`.
    pub http_version: &'static str,
    pub timer_backend: &'static str,
    pub static_header_names: Vec<String>,
    pub protocol_surface: &'static str,
    pub plan: RunPlan,
    pub token_dictionary: TokenDictionaryManifest,
    pub request_count: usize,
    pub budgeted_requests: usize,
    pub unbudgeted_requests: usize,
    pub planned_aborts: usize,
    pub succeeded: usize,
    pub failed: usize,
    pub output_length_matches: usize,
    pub output_length_mismatches: usize,
    pub missing_output_usage: usize,
    pub planned_abort_matches: usize,
    pub planned_abort_mismatches: usize,
    pub scheduler_wake_lag_ms: Percentiles,
    pub dispatch_lag_ms: Percentiles,
    pub local_admission_lag_ms: Percentiles,
    pub performance: Performance,
    /// The run reached `stop_after` before sending every planned request.
    pub stopped_early: bool,
    /// Every sent request succeeded with its planned output length.
    pub passed: bool,
    pub total_time_ms: f64,
}

/// Target performance observed by the client over the whole run.
#[derive(Debug, Clone, Serialize)]
pub struct Performance {
    pub requests_per_second: f64,
    pub input_tokens_per_second: f64,
    pub output_tokens_per_second: f64,
    /// Time to the first streamed output token.
    pub ttft_ms: Percentiles,
    pub request_latency_ms: Percentiles,
    /// Mean time per output token after the first, per request.
    pub tpot_ms: Percentiles,
}

/// What the run planned, over the top-level trees it started.
#[derive(Debug, Clone, Serialize)]
pub struct RunPlan {
    pub profile_digest_sha256: String,
    pub top_level_sessions: usize,
    /// Configured top-level streams; absent for arrival schedules.
    pub concurrent_sessions: Option<usize>,
    /// Descendant protocol sessions generated by delegation and swarms.
    pub subagent_sessions: usize,
    pub requests: usize,
    pub input_tokens: u64,
    pub output_tokens: u64,
}

#[derive(Clone)]
struct ReplayContext {
    client: reqwest::Client,
    base: Instant,
}

struct PreparedRequest {
    metadata: PreparedMetadata,
    http_request: reqwest::Request,
}

#[derive(Clone)]
struct PreparedMetadata {
    ordinal: usize,
    source_request_id: String,
    source_x_request_id: Option<String>,
    replay_request_id: String,
    agent_context: Option<AgentContext>,
    input_tokens: usize,
    expected_output_tokens: Option<u32>,
    compaction_attempt: Option<GeneratedCompactionAttempt>,
}

struct RequestExecution {
    /// Harness headers rendered for this request.
    headers: headers::Headers,
    output_budget_tokens: Option<u32>,
    compaction_attempt: Option<GeneratedCompactionAttempt>,
    /// Last request of its protocol session; see `ReplayOptions::dynamo_session_final`.
    session_final: bool,
}

fn millis(duration: Duration) -> f64 {
    duration.as_secs_f64() * 1000.0
}

fn duration_ns(duration: Duration) -> u64 {
    duration.as_nanos().min(u64::MAX as u128) as u64
}

